package Monos;

/**
 *
 * @author Usuario
 */
public class Monos {

    private int coste;
    private int dps;

    public Monos(int coste, int dps) {
        this.coste = coste;
        this.dps = dps;
    }

    public int getCoste() {
        return coste;
    }

    public void setCoste(int coste) {
        this.coste = coste;
    }

    public int getDps() {
        return dps;
    }

    public void setDps(int dps) {
        this.dps = dps;
    }

}
